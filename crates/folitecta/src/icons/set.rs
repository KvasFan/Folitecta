//! The icons of the interface, by what they mean. The drawings are Tabler
//! Icons (MIT licence) from the `icondata_tb` crate: a name here says what an
//! icon stands for, so its drawing can change in one place.

use icondata_core::IconData;
use icondata_tb as tb;

