//! Generates a small demonstration PDF that exercises the core API.
//!
//! Usage: `cargo run -p folitecta-core --example make_sample -- out.pdf`

use folitecta_core::marks::{MarkPosition, TextMarkOptions};
use folitecta_core::{Document, Markup, OutlineItem, Shape};

fn main() -> Result<(), Box<dyn std::error::Error>> {
    let out = std::env::args()
        .nth(1)
        .unwrap_or_else(|| "sample.pdf".to_string());
    let mut doc = Document::new_blank(4, 595.0, 842.0)?;
    let all: Vec<usize> = (0..4).collect();

    doc.set_info(
        "Folitecta sample document",
        "Folitecta",
        "Demonstration of the core API",
        "folitecta, pdf, rust",
    )?;
    doc.add_header_footer(
        &all,
        ["{title}", "", "{date}"],
        ["", "Page {page} of {pages}", "Folitecta {author}"],
        10.0,
        28.0,
        [0.2, 0.2, 0.3],
    )?;

    // Page 1: a title block and some comments.
    doc.add_free_text(
        0,
        [60.0, 700.0, 535.0, 790.0],
        "Folitecta\nA free PDF editor written in Rust",
        "Folitecta",
        26.0,
        [0.3, 0.27, 0.9],
        false,
    )?;
    doc.add_free_text(
        0,
        [60.0, 560.0, 535.0, 680.0],
        "This document was generated by the folitecta-core example.\nEvery element on these pages was created through the public API:\nfree text, shapes, lines, ink, highlights, notes, bookmarks, links,\nattachments, headers and footers, watermarks and page numbers.",
        "Folitecta",
        12.0,
        [0.1, 0.1, 0.1],
        true,
    )?;
    doc.add_shape(
        0,
        Shape::Square,
        [60.0, 380.0, 280.0, 520.0],
        [0.86, 0.15, 0.15],
        Some([1.0, 0.95, 0.85]),
        2.0,
        "Folitecta",
        "A rectangle",
    )?;
    doc.add_shape(
        0,
        Shape::Circle,
        [315.0, 380.0, 535.0, 520.0],
        [0.1, 0.45, 0.85],
        Some([0.9, 0.95, 1.0]),
        2.0,
        "Folitecta",
        "An ellipse",
    )?;
    doc.add_line(
        0,
        (60.0, 340.0),
        (535.0, 340.0),
        [0.2, 0.2, 0.2],
        1.5,
        true,
        "Folitecta",
        "An arrow",
    )?;
    doc.add_ink(
        0,
        &[vec![
            (80.0, 250.0),
            (140.0, 310.0),
            (200.0, 250.0),
            (260.0, 310.0),
            (320.0, 250.0),
        ]],
        [0.2, 0.2, 0.75],
        2.5,
        "Folitecta",
    )?;
    doc.add_text_markup(
        0,
        Markup::Highlight,
        &[[60.0, 690.0, 300.0, 690.0, 60.0, 672.0, 300.0, 672.0]],
        [1.0, 0.9, 0.2],
        "Folitecta",
        "",
    )?;
    doc.add_note(
        0,
        500.0,
        300.0,
        "Sticky notes keep the author, date and text.",
        "Folitecta",
        [1.0, 0.85, 0.2],
    )?;
    doc.add_uri_link(
        0,
        [60.0, 150.0, 300.0, 175.0],
        "https://github.com/KvasExpert/Folitecta",
    )?;
    doc.add_free_text(
        0,
        [60.0, 150.0, 300.0, 175.0],
        "github.com/KvasExpert/Folitecta",
        "Folitecta",
        11.0,
        [0.1, 0.3, 0.8],
        false,
    )?;

    // Page 2: a watermark and Bates numbers.
    doc.add_text_watermark(
        &[1],
        &TextMarkOptions {
            text: "SAMPLE".into(),
            ..TextMarkOptions::default()
        },
    )?;
    doc.add_page_numbers(
        &all,
        "FOLI-{bates:6}",
        1,
        MarkPosition::TopRight,
        9.0,
        52.0,
        [0.3, 0.3, 0.3],
    )?;

    // Page 3: a page link back to the first page.
    doc.add_free_text(
        2,
        [60.0, 740.0, 400.0, 770.0],
        "Back to the first page",
        "Folitecta",
        12.0,
        [0.1, 0.3, 0.8],
        false,
    )?;
    doc.add_page_link(2, [60.0, 740.0, 400.0, 770.0], 0)?;

    // Page 4 rotated, to exercise rotation-aware marks.
    doc.rotate_pages(&[3], 90)?;
    doc.add_text_watermark(
        &[3],
        &TextMarkOptions {
            text: "LANDSCAPE".into(),
            rotation: 0.0,
            position: MarkPosition::Center,
            ..TextMarkOptions::default()
        },
    )?;

    doc.set_outline(&[
        OutlineItem {
            title: "Overview".into(),
            page: Some(0),
            children: vec![OutlineItem::new("Comments", Some(0))],
        },
        OutlineItem::new("Watermark", Some(1)),
        OutlineItem::new("Links", Some(2)),
        OutlineItem::new("Rotated page", Some(3)),
    ])?;
    doc.add_attachment(
        "readme.txt",
        b"Generated by folitecta-core.".to_vec(),
        "A tiny attachment",
        Some("text/plain"),
    )?;

    doc.save_as(&out)?;
    println!(
        "wrote {out} ({} pages, {} bytes)",
        doc.page_count(),
        doc.bytes().len()
    );
    Ok(())
}
