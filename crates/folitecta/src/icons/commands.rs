/// The name of the icon of a command (see [`super::set::data`]).
pub fn for_command(id: &str) -> &'static str {
    if let Some((_, icon)) = BY_ID.iter().find(|(i, _)| *i == id) {
        return icon;
    }
    let lower = id.to_lowercase();
    BY_WORD
        .iter()
        .find(|(words, _)| words.iter().any(|w| lower.contains(w)))
        .map(|(_, icon)| *icon)
        .unwrap_or("content")
}
